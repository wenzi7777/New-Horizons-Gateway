// @ts-check
/**
 * Generates the firmware's and the Desktop's copies of the app contract from
 * opset.mjs, so there is one hand-written source instead of three that tests
 * keep chasing:
 *
 *   - firmware/newhorizons_os/AppContract.h  (NewHorizonsOS-OTA)
 *   - backend/newhorizons_backend/app_contract.py  (New-Horizons-Desktop)
 *
 * `node sdk/bin/nhos.mjs gen-contract --firmware <dir> --backend <dir>`
 * writes them; `--check` fails when a committed copy differs. Pure functions
 * of opset.mjs, no I/O here, so the Desktop's vendored SDK can regenerate and
 * compare too.
 */

import {
  CAPABILITIES,
  DEVICE_CAPABILITIES,
  FEATURE_FIELDS,
  IMU_FIELDS,
  LED_COLOURS,
  MAG_FIELDS,
  MAX_EVENT_NAME,
  MAX_NODES,
  MAX_PACKAGE_BYTES,
  OPS,
} from "./opset.mjs";
import {
  NATIVE_LAYOUT,
  OPERAND_BYTES,
  VM_EVENTS,
  VM_FAULTS,
  VM_FUEL_CHECK,
  VM_HEADER_BYTES,
  VM_IMAGE_VERSION,
  VM_INSN_NS,
  VM_MAX_ARENA,
  VM_MAX_CALL_DEPTH,
  VM_MAX_CODE,
  VM_MAX_CONSTS,
  VM_MAX_FUNCTIONS,
  VM_MAX_NODES,
  VM_MAX_STACK,
  VM_MAX_STRING,
  VM_MAX_STRINGS,
  VM_OPCODES,
  VM_STARVED_MS,
  VM_SYSCALLS,
} from "./vmset.mjs";

const NOTICE = "GENERATED by `node sdk/bin/nhos.mjs gen-contract` (NHOS-App-Library) from sdk/lib/opset.mjs.";
const DO_NOT_EDIT = "Do not edit: change opset.mjs and regenerate; CI fails when this copy drifts.";

/** `region_row_centroid` -> `RegionRowCentroid`. @param {string} name */
const camel = (name) => name.replace(/(^|_)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

// The firmware spelled one capability differently before this was generated.
/** @type {Record<string, string>} */
const CAP_CPP_NAMES = { drive_ext_led: "ExtLed" };
/** @param {string} name */
export const capabilityConstant = (name) => `kAppCap${CAP_CPP_NAMES[name] ?? camel(name)}`;

/** Every capability the device knows, by bit. */
function allCapabilities() {
  return Object.entries({ ...CAPABILITIES, ...DEVICE_CAPABILITIES }).sort((a, b) => a[1] - b[1]);
}

/** @param {number} bit */
const shiftOf = (bit) => Math.log2(bit);

/** @returns {string} the whole of AppContract.h */
export function firmwareHeader() {
  const out = [];
  out.push(`// ${NOTICE}`);
  out.push(`// ${DO_NOT_EDIT}`);
  out.push("//");
  out.push("// Plain C++ (no Arduino), so FlowMath.h can include it in the App Library's");
  out.push("// desktop harness too.");
  out.push("#pragma once");
  out.push("");
  out.push("#include <stdint.h>");
  out.push("");
  out.push("namespace nhos {");
  out.push("");

  // --- capabilities -----------------------------------------------------------
  out.push("// What an app may touch and, for the event sources, what it is woken for.");
  out.push("// Explained where it is used: App.h.");
  out.push("enum AppCapability : uint16_t {");
  out.push("  kAppCapNone = 0,");
  for (const [name, bit] of allCapabilities()) out.push(`  ${capabilityConstant(name)} = 1 << ${shiftOf(bit)},`);
  out.push("};");
  out.push("");
  out.push("struct AppCapabilityName {");
  out.push("  const char* name;");
  out.push("  uint16_t bit;");
  out.push("};");
  out.push("// The names a package's manifest may use. `budget` is set by the device; the");
  out.push("// App Library never declares it, but a hand-made package may.");
  out.push("static constexpr AppCapabilityName kAppCapabilityNames[] = {");
  for (const [name] of allCapabilities()) out.push(`    {"${name}", ${capabilityConstant(name)}},`);
  out.push("};");
  out.push("");

  // --- ops --------------------------------------------------------------------
  const ops = Object.values(OPS);
  out.push("// The operators a flow graph can use, in opset.mjs order. The device persists");
  out.push("// op numbers beside counter values, so this order is append-only.");
  out.push("enum class FlowOp : uint8_t {");
  out.push("  Invalid = 0,");
  for (const spec of ops) out.push(`  ${camel(spec.name)},`);
  out.push("};");
  out.push(`static constexpr uint8_t kFlowOpCount = ${ops.length + 1};  // with Invalid`);
  out.push("");
  out.push("struct FlowOpInfo {");
  out.push("  const char* name;");
  out.push("  uint8_t inputs;       // earlier nodes it consumes");
  out.push("  bool sweep;           // costed per cell");
  out.push("  uint16_t nsPerCell;   // sweep cost per cell");
  out.push("  uint16_t nsFlat;      // scalar cost");
  out.push("  bool windowed;        // takes `window` frames from the slot's pool");
  out.push("  bool region;          // r0..c1 (and `rel`) select a rectangle");
  out.push("  uint16_t capability;  // what a graph using it must declare, or 0");
  out.push("};");
  out.push("static constexpr FlowOpInfo kFlowOps[kFlowOpCount] = {");
  out.push(`    {"invalid", 0, false, 0, 0, false, false, kAppCapNone},`);
  for (const spec of ops) {
    const fields = [
      `"${spec.name}"`,
      spec.inputs,
      spec.sweep,
      spec.nsPerCell,
      spec.nsFlat,
      spec.windowKey !== null,
      spec.required.includes("r0"),
      spec.capability ? capabilityConstant(spec.capability) : "kAppCapNone",
    ];
    out.push(`    {${fields.join(", ")}},`);
  }
  out.push("};");
  out.push("");

  // --- fields -----------------------------------------------------------------
  /**
   * @param {string} enumName
   * @param {string} tableName
   * @param {readonly string[]} names
   * @param {string} comment
   */
  const fieldEnum = (enumName, tableName, names, comment) => {
    out.push(`// ${comment}`);
    out.push(`enum class ${enumName} : uint8_t {`);
    names.forEach((name, i) => out.push(`  ${camel(name)}${i === 0 ? " = 0" : ""},`));
    out.push("  Count,");
    out.push("};");
    out.push(`static constexpr const char* ${tableName}[] = {`);
    for (const name of names) out.push(`    "${name}",`);
    out.push("};");
    out.push("");
  };
  fieldEnum("FeatureField", "kFeatureFieldNames", FEATURE_FIELDS, "feature_get(field): what one features sweep produces, in wire order.");
  fieldEnum("ImuField", "kImuFieldNames", IMU_FIELDS, "imu(field), in wire order: g, deg/s, g, deg/s, deg, deg.");
  fieldEnum("MagField", "kMagFieldNames", MAG_FIELDS, "mag(field), in wire order: microtesla, heading in degrees.");

  // --- colours ----------------------------------------------------------------
  out.push("struct FlowColour {");
  out.push("  const char* name;");
  out.push("  uint8_t rgb[3];");
  out.push("};");
  out.push("// The whole palette an `rgb` field may name.");
  out.push("static constexpr FlowColour kFlowColours[] = {");
  for (const [name, [r, g, b]] of Object.entries(LED_COLOURS)) out.push(`    {"${name}", {${r}, ${g}, ${b}}},`);
  out.push("};");
  out.push("");
  // --- the app VM (vmset.mjs, docs/vm.md) -------------------------------------
  out.push("// NHVM/1. Opcodes are the index into kVmOps; APPEND only.");
  out.push(`static constexpr uint8_t kVmImageVersion = ${VM_IMAGE_VERSION};`);
  out.push(`static constexpr uint8_t kVmHeaderBytes = ${VM_HEADER_BYTES};`);
  out.push(`static constexpr uint16_t kVmMaxCode = ${VM_MAX_CODE};`);
  out.push(`static constexpr uint16_t kVmMaxConsts = ${VM_MAX_CONSTS};`);
  out.push(`static constexpr uint16_t kVmMaxArena = ${VM_MAX_ARENA};`);
  out.push(`static constexpr uint8_t kVmMaxStack = ${VM_MAX_STACK};`);
  out.push(`static constexpr uint8_t kVmMaxFunctions = ${VM_MAX_FUNCTIONS};`);
  out.push(`static constexpr uint8_t kVmMaxStrings = ${VM_MAX_STRINGS};`);
  out.push(`static constexpr uint8_t kVmMaxString = ${VM_MAX_STRING};`);
  out.push(`static constexpr uint8_t kVmMaxCallDepth = ${VM_MAX_CALL_DEPTH};`);
  out.push(`static constexpr uint8_t kVmMaxNodes = ${VM_MAX_NODES};`);
  out.push(`static constexpr uint16_t kVmFuelCheck = ${VM_FUEL_CHECK};`);
  out.push(`static constexpr uint32_t kVmStarvedMs = ${VM_STARVED_MS};`);
  out.push(`static constexpr uint16_t kVmInsnNs = ${VM_INSN_NS};`);
  out.push("enum class VmOp : uint8_t {");
  for (const spec of VM_OPCODES) out.push(`  ${camel(spec.name)} = ${spec.code},`);
  out.push("};");
  out.push(`static constexpr uint8_t kVmOpCount = ${VM_OPCODES.length};`);
  out.push("// Operand layout: 0 none, 1 u8, 2 u16, 3 i16, 4 u16 u16, 5 nat (u8 u16 u16).");
  out.push("struct VmOpInfo {");
  out.push("  const char* name;");
  out.push("  uint8_t operands;");
  out.push("  uint8_t size;   // bytes with the opcode");
  out.push("  int8_t pops;    // -1: depends on the operand");
  out.push("  int8_t pushes;");
  out.push("};");
  const operandKinds = { "": 0, u8: 1, u16: 2, i16: 3, u16u16: 4, nat: 5 };
  out.push("static constexpr VmOpInfo kVmOps[kVmOpCount] = {");
  for (const spec of VM_OPCODES) {
    const size = 1 + OPERAND_BYTES[/** @type {keyof typeof OPERAND_BYTES} */ (spec.operands)];
    out.push(`    {"${spec.name}", ${operandKinds[/** @type {keyof typeof operandKinds} */ (spec.operands)]}, ${size}, ${spec.pops}, ${spec.pushes}},`);
  }
  out.push("};");
  out.push("");
  out.push("// Handler entry points, by event id.");
  out.push("enum class VmEvent : uint8_t {");
  for (const [name, id] of Object.entries(VM_EVENTS)) out.push(`  ${camel(name)} = ${id},`);
  out.push("};");
  out.push(`static constexpr uint8_t kVmEventCount = ${Object.keys(VM_EVENTS).length};`);
  out.push("");
  out.push("// Why an app faulted; kVmFaultNames[code].");
  out.push("static constexpr const char* kVmFaultNames[] = {");
  for (const name of VM_FAULTS) out.push(`    "${name}",`);
  out.push("};");
  out.push("");
  out.push("// Native operators: the FlowOps a NAT instruction may run, with their");
  out.push("// parameter-record length and state slots (a windowed op adds its window).");
  out.push("struct VmNativeInfo {");
  out.push("  uint8_t params;  // 0xFF: not a native op");
  out.push("  uint8_t state;");
  out.push("};");
  out.push("static constexpr VmNativeInfo kVmNatives[kFlowOpCount] = {");
  out.push("    {0xFF, 0},  // invalid");
  for (const name of Object.keys(OPS)) {
    const layout = NATIVE_LAYOUT[name];
    out.push(layout ? `    {${layout.params.length}, ${layout.state}},  // ${name}` : `    {0xFF, 0},  // ${name}: plain instructions`);
  }
  out.push("};");
  out.push("");
  out.push("// System calls, by id; APPEND only.");
  out.push("struct VmSyscallInfo {");
  out.push("  const char* name;");
  out.push("  uint16_t capability;");
  out.push("  uint8_t args;");
  out.push("  uint8_t results;");
  out.push("  uint8_t fuel;");
  out.push("};");
  out.push(`static constexpr uint8_t kVmSyscallCount = ${VM_SYSCALLS.length};`);
  out.push("static constexpr VmSyscallInfo kVmSyscalls[kVmSyscallCount] = {");
  for (const sys of VM_SYSCALLS) {
    out.push(`    {"${sys.name}", ${sys.cap ? capabilityConstant(sys.cap) : "kAppCapNone"}, ${sys.args}, ${sys.results}, ${sys.fuel}},`);
  }
  out.push("};");
  out.push("");
  out.push("}  // namespace nhos");
  out.push("");
  return out.join("\n");
}

/** @param {Iterable<string>} names */
function pySet(names) {
  const sorted = [...names].sort();
  const lines = [];
  let line = "   ";
  for (const name of sorted) {
    const item = ` "${name}",`;
    if (line.length + item.length > 88) {
      lines.push(line);
      line = "   ";
    }
    line += item;
  }
  lines.push(line);
  return `{\n${lines.join("\n")}\n}`;
}

/** @returns {string} the whole of app_contract.py */
export function backendModule() {
  return [
    `"""${NOTICE}`,
    "",
    DO_NOT_EDIT,
    '"""',
    "",
    "# Every op a flow package may use.",
    `KNOWN_OPS = ${pySet(Object.keys(OPS))}`,
    "",
    "# Capabilities a package may declare.",
    `CAPABILITIES = ${pySet(Object.keys(CAPABILITIES))}`,
    "",
    `MAX_NODES = ${MAX_NODES}`,
    `MAX_PACKAGE_BYTES = ${MAX_PACKAGE_BYTES}`,
    `MAX_EVENT_NAME = ${MAX_EVENT_NAME}`,
    "",
  ].join("\n");
}

