export type SplashKey = Key;
export const SPLASH_STRINGS: Record<Locale, Record<Key, string>> = { en, ja, 'zh-CN': zhCN };

export function splashT(locale: Locale, key: Key, vars?: Record<string, string | number>): string {
  let text = SPLASH_STRINGS[locale]?.[key] ?? en[key];
  for (const [name, value] of Object.entries(vars ?? {})) text = text.split(`{${name}}`).join(String(value));
  return text;
}
