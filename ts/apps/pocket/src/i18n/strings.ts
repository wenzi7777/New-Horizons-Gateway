export function isAppKey(key: string): key is AppKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

function fill(text: string, vars?: Readonly<Record<string, unknown>>): string {
  for (const [name, value] of Object.entries(vars ?? {})) {
    text = text.split(`{${name}}`).join(value === undefined || value === null || value === '' ? '-' : String(value));
  }
  return text;
}

/** A UI string in `locale`, app strings first, then the shared Gateway ones; English as the fallback. */
export function translate(locale: Locale, key: Key, vars?: Readonly<Record<string, unknown>>): string {
  if (isAppKey(key)) return fill(appDictionaries[locale]?.[key] || en[key] || key, vars);
  if (isMessageKey(key)) return fill(sharedDictionaries[locale]?.[key] || sharedDictionaries.en[key] || key, vars);
  return key;
}

/** A device or engine error code as text: the shared `err_<code>` string when there is one. */
export function errorText(locale: Locale, code: string): string {
  const key = `err_${code}`;
  return isMessageKey(key) ? translate(locale, key) : code;
}
