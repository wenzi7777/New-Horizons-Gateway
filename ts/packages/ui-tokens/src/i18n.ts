export type Locale = 'en' | 'ja' | 'zh-CN';
export const LOCALES: readonly Locale[] = ['en', 'ja', 'zh-CN'];
export const DEFAULT_LOCALE: Locale = 'en';
/** Where the web UI remembers the chosen language (localStorage). */
export const LANGUAGE_KEY = 'newhorizons-gateway-language';

export const dictionaries: { readonly [L in Locale]: Dictionary } = { en, ja, 'zh-CN': zhCN };

/**
 * One language tag (a stored choice, navigator.language, an OS locale such
 * as "ja_JP.UTF-8") as a supported locale: Japanese and Simplified Chinese
 * by prefix, everything else (Traditional Chinese included) English. Same
 * rule as the web UI's normalizeLanguage().
 */
export function normalizeLocale(tag: string | null | undefined): Locale {
  const input = String(tag ?? '').trim().toLowerCase().replace(/_/g, '-');
  if (input === 'ja' || input.startsWith('ja-')) return 'ja';
  if (input === 'zh' || input.startsWith('zh-cn') || input.startsWith('zh-hans') || input === 'zh-sg') return 'zh-CN';
  return 'en';
}

/**
 * The locale for a list of preferred languages, most preferred first
 * (navigator.languages, Intl/OS locales). Like the web UI, only the first
 * entry counts: a Japanese system that also lists English gets Japanese, an
 * unsupported first choice gets English rather than a later entry.
 */
export function resolveLocale(preferred: readonly (string | null | undefined)[]): Locale {
  return normalizeLocale(preferred[0]);
}

/**
 * A UI string: the locale's, else English's, else the key itself, with
 * `{name}` placeholders filled from `vars` (empty/missing values show "-",
 * as in the web UI's fmt()).
 */
export function t(locale: Locale, key: MessageKey, vars?: Readonly<Record<string, unknown>>): string {
  let text: string = dictionaries[locale]?.[key] || en[key] || key;
  for (const [name, value] of Object.entries(vars ?? {})) {
    text = text.split(`{${name}}`).join(value === undefined || value === null || value === '' ? '-' : String(value));
  }
  return text;
}

/** Whether a computed key (e.g. `err_${code}` from a server error) has a string. */
export function isMessageKey(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}
